/**
 * Extract domain from email
 */
export function getEmailDomain(email) {
  if (!email || typeof email !== 'string') return null;
  const parts = email.toLowerCase().trim().split('@');
  return parts.length === 2 ? parts[1] : null;
}

/**
 * Check if email format is valid
 */
export function isValidEmailFormat(email) {
  if (!email || typeof email !== 'string') return false;
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  return emailRegex.test(email.trim());
}

/**
 * Check if email is from a disposable/temporary provider
 */
export function isDisposableEmail(email) {
  const domain = getEmailDomain(email);
  if (!domain) return true; // Invalid email = treat as disposable
  return DISPOSABLE_EMAIL_DOMAINS.includes(domain.toLowerCase());
}

/**
 * Check if email is from an allowed provider (whitelist approach)
 * Use this for stricter validation
 */
export function isAllowedEmailProvider(email) {
  const domain = getEmailDomain(email);
  if (!domain) return false;
  
  const lowerDomain = domain.toLowerCase();
  
  // Check if it's in our allowed list
  if (ALLOWED_EMAIL_DOMAINS.includes(lowerDomain)) {
    return true;
  }
  
  // Allow corporate/business emails (custom domains)
  // These typically have proper MX records and aren't disposable
  // You can add additional validation here if needed
  
  return false;
}

/**
 * Comprehensive email validation
 * Returns: { valid: boolean, error: string | null }
 */
export function validateEmail(email, useStrictMode = false) {
  // Trim and lowercase
  const cleanEmail = email?.trim().toLowerCase();
  
  // Check if empty
  if (!cleanEmail) {
    return { valid: false, error: 'Email is required' };
  }
  
  // Check format
  if (!isValidEmailFormat(cleanEmail)) {
    return { valid: false, error: 'Please enter a valid email address' };
  }
  
  // Check for disposable email
  if (isDisposableEmail(cleanEmail)) {
    return {
      valid: false,
      error: 'Temporary or disposable emails are not allowed. Please use a real email address (Gmail, Outlook, Yahoo, etc.)',
    };
  }
  
  // Strict mode: only allow known providers
  if (useStrictMode && !isAllowedEmailProvider(cleanEmail)) {
    return {
      valid: false,
      error: 'Please use an email from a major provider like Gmail, Outlook, Yahoo, or iCloud',
    };
  }
  
  return { valid: true, error: null };
}

